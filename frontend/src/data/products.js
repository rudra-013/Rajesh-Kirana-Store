export const getProductById = (id) =>
  products.find((p) => p.id === parseInt(id, 10)) || null;

export const getProductsByCategory = (cat, subcategory) => {
  if (!cat) return [];
  const normalized = cat.toLowerCase().trim();

  const list = products.filter((p) => {
    const pCat = p.category.toLowerCase().trim();
    // exact slug match
    if (pCat === normalized) return true;

    // exact name match
    if (p.categoryName && p.categoryName.toLowerCase() === normalized) return true;

    // category aliases
    if (
      (normalized.includes('masala') || normalized.includes('oil') || normalized.includes('ghee') || normalized.includes('spices')) &&
      pCat === 'masala-oil-more'
    )
      return true;

    if (
      (normalized.includes('fruit') || normalized.includes('veg')) &&
      pCat === 'fruits-vegetables'
    )
      return true;

    if (
      (normalized.includes('dairy') || normalized.includes('bread') || normalized.includes('egg')) &&
      pCat === 'dairy-bread-eggs'
    )
      return true;

    if (
      (normalized.includes('snack') || normalized.includes('munch')) &&
      pCat === 'snacks-munchies'
    )
      return true;

    if (
      (normalized.includes('drink') || normalized.includes('juice') || normalized.includes('beverage')) &&
      (pCat === 'cold-drinks-juices' || pCat === 'beverages')
    )
      return true;

    if (
      (normalized.includes('atta') || normalized.includes('rice') || normalized.includes('dal')) &&
      pCat === 'atta-rice-dal'
    )
      return true;

    if (
      (normalized.includes('breakfast') || normalized.includes('instant')) &&
      pCat === 'breakfast-instant-food'
    )
      return true;

    if (
      (normalized.includes('sweet') || normalized.includes('tooth') || normalized.includes('chocolate')) &&
      pCat === 'sweet-tooth'
    )
      return true;

    if (
      (normalized.includes('bakery') || normalized.includes('biscuit')) &&
      pCat === 'bakery-biscuits'
    )
      return true;

    if (
      (normalized.includes('tea') || normalized.includes('coffee')) &&
      pCat === 'tea-coffee-drinks'
    )
      return true;

    if (normalized.includes('baby') && pCat === 'baby-care') return true;
    if (normalized.includes('pet') && pCat === 'pet-care') return true;
    if ((normalized.includes('clean') || normalized.includes('household')) && (pCat === 'cleaning-essentials' || pCat === 'household-needs')) return true;
    if (normalized.includes('pharma') && pCat === 'pharma-wellness') return true;
    if (normalized.includes('personal') && pCat === 'personal-care') return true;

    return false;
  });

  if (subcategory && subcategory !== 'All') {
    return list.filter((p) => p.subcategory && p.subcategory.toLowerCase() === subcategory.toLowerCase());
  }

  return list;
};

export const searchProducts = (query) => {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      (p.categoryName && p.categoryName.toLowerCase().includes(q)) ||
      (p.subcategory && p.subcategory.toLowerCase().includes(q)) ||
      (p.description && p.description.toLowerCase().includes(q))
  );
};
